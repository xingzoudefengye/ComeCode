export function createProviderSettingsService(
  facade: ProviderSettingsFacade,
  ensureReady: () => Promise<void> = async () => {},
  testConnectivity?: ProviderSettingsConnectivityTester,
): IProviderSettingsService {
  // 跨进程/跨端并发时 UI 可能按已消失的 providerId 操作。先刷新 Registry 与来源再重试一次，
  // 仍失败才提示用户刷新，而不是把底层的"Provider 不存在"直接抛到界面。
  const runWithStaleRetry = async <T>(reason: string, operation: () => Promise<T>): Promise<T> => {
    try {
      return await operation();
    } catch (error) {
      if (!isStaleProviderError(error)) throw error;
      await facade.refresh(`stale-retry:${reason}`);
      try {
        return await operation();
      } catch (retryError) {
        if (!isStaleProviderError(retryError)) throw retryError;
        throw new Error(formatStaleProviderMessage(retryError));
      }
    }
  };
  return {
    onDidChange: toEvent((listener) => facade.onDidChange(listener)),
    getView: async () => {
      await ensureReady();
      return facade.getView();
    },
    refresh: async (reason) => {
      await ensureReady();
      return facade.refresh(reason);
    },
    createPersonalProvider: async (input) => {
      await ensureReady();
      return facade.createPersonalProvider(input);
    },
    resolveModelConfig: async (input) => {
      await ensureReady();
      return facade.resolveModelConfig(input);
    },
    savePersonalProviderOverlay: async (providerId, config, metadata) => {
      await ensureReady();
      return runWithStaleRetry("save-provider", () =>
        facade.savePersonalProviderOverlay(providerId, config, metadata),
      );
    },
    deletePersonalProvider: async (providerId) => {
      await ensureReady();
      return runWithStaleRetry("delete-provider", () =>
        facade.deletePersonalProvider(providerId),
      );
    },
    reorderPersonalProviders: async (providerIds) => {
      await ensureReady();
      return runWithStaleRetry("reorder-providers", () =>
        facade.reorderPersonalProviders(providerIds),
      );
    },
    reorderPersonalModels: async (providerId, modelIds) => {
      await ensureReady();
      return runWithStaleRetry("reorder-models", () =>
        facade.reorderPersonalModels(providerId, modelIds),
      );
    },
    addPersonalModel: async (providerId, modelId, config, useRecommendedConfig) => {
      await ensureReady();
      return runWithStaleRetry("add-model", () =>
        facade.addPersonalModel(providerId, modelId, config, useRecommendedConfig),
      );
    },
    renamePersonalModel: async (providerId, currentModelId, nextModelId) => {
      await ensureReady();
      return runWithStaleRetry("rename-model", () =>
        facade.renamePersonalModel(providerId, currentModelId, nextModelId),
      );
    },
    deletePersonalModel: async (providerId, modelId) => {
      await ensureReady();
      return runWithStaleRetry("delete-model", () =>
        facade.deletePersonalModel(providerId, modelId),
      );
    },
    savePersonalModelDraft: async (input) => {
      await ensureReady();
      return runWithStaleRetry("save-model-draft", () =>
        facade.savePersonalModelDraft(input),
      );
    },
    setPersonalModelEnabled: async (providerId, modelId, enabled) => {
      await ensureReady();
      return runWithStaleRetry("set-model-enabled", () =>
        facade.setPersonalModelEnabled(providerId, modelId, enabled),
      );
    },
    testModelConnectivity: async (input) => {
      await ensureReady();
      if (!testConnectivity) {
        throw new Error("当前 Environment 未装配模型连通性测试能力");
      }
      await facade.waitForProviderOperations(input.providerId);
      // 禁用对象仍存在于配置视图，但不进入执行 Registry；不能把未发布误报成配置丢失。
      // 只消费操作完成后的公共资格，不另查 Key、权益，也不替代目标 Environment 最终校验。
      const provider = facade
        .getView()
        .providers.find((item) => item.providerId === input.providerId);
      const model = provider?.models.find((item) => item.modelId === input.modelId);
      const unavailable =
        !provider || !provider.enabled
          ? "provider-unavailable"
          : !model || !model.enabled || model.issues.length > 0
            ? "model-unavailable"
            : !provider.executable
              ? "provider-unavailable"
              : !model.executable
                ? "model-unavailable"
                : undefined;
      if (unavailable) {
        return {
          success: false,
          error: {
            code: unavailable,
            message:
              unavailable === "provider-unavailable"
                ? "This provider is currently unavailable for connectivity testing."
                : "This model is currently unavailable for connectivity testing.",
          },
        };
      }
      return testConnectivity({
        workspacePath: input.workspacePath,
        ...(input.workspaceIdentity ? { workspaceIdentity: input.workspaceIdentity } : {}),
        providerId: input.providerId,
        modelId: input.modelId,
      });
    },
  };
}

/** 兼容不同打包实例：结构化判定，不依赖 instanceof 的单一类身份。 */
function isStaleProviderError(error: unknown): error is ProviderMutationStaleError {
  return (
    error instanceof ProviderMutationStaleError ||
    (typeof error === "object" &&
      error !== null &&
      (error as { name?: unknown }).name === "ProviderMutationStaleError")
  );
}

function formatStaleProviderMessage(error: ProviderMutationStaleError): string {
  const available = error.availableProviderIds.length
    ? error.availableProviderIds.join("、")
    : "无";
  return `该供应商已不存在（${error.providerId}），界面可能已过期，请刷新后重试。当前可用供应商：${available}`;
}

export function createModelSelectionService(
  facade: ModelSelectionFacade,
  ensureReady: () => Promise<void> = async () => {},
  configuredDefaultSource?: ModelSelectionConfiguredDefaultSource,
): IModelSelectionService & { dispose(): void } {
  const log = createServiceLogger("model-selection");
  let revision = 0;
  let disposed = false;
  const listeners = new Set<(view: ModelSelectionView) => void>();
  const getView = async (input?: ModelSelectionViewInput): Promise<ModelSelectionView> => {
    await ensureReady();
    if (disposed) throw new Error("ModelSelectionService 已 dispose");
    const configuredDefault = await configuredDefaultSource?.read();
    if (disposed) throw new Error("ModelSelectionService 已 dispose");
    const base = facade.getView(configuredDefault);
    if (revision < base.revision) revision = base.revision;
    return facade.getView(configuredDefault, revision, input);
  };
  const emit = (): void => {
    if (disposed) return;
    revision += 1;
    void getView().then(
      (view) => {
        if (disposed) return;
        for (const listener of listeners) listener(view);
      },
      (error: unknown) => {
        // Registry 事件触发的异步 View 重建没有 owner；Host dispose 后它仍会继续
        // 读取已释放的配置仓库，并形成未处理 rejection。dispose 是明确的取消边界；仅在服务
        // 仍存活时记录真实读取失败。
        if (disposed) return;
        log.warn(undefined, `ModelSelection View 刷新失败: ${String(error)}`);
      },
    );
  };
  const disposeFacade = facade.onDidChange(emit);
  const disposeConfiguredDefault = configuredDefaultSource?.onDidChange?.(emit);

  return {
    onDidChange: (listener) => {
      listeners.add(listener);
      return { dispose: () => listeners.delete(listener) };
    },
    getView,
    dispose() {
      if (disposed) return;
      disposed = true;
      disposeFacade();
      disposeConfiguredDefault?.();
      listeners.clear();
    },
  };
}

function toEvent<T>(subscribe: (listener: (event: T) => void) => () => void): Event<T> {
  return (listener) => {
    const dispose = subscribe(listener);
    return { dispose };
  };
}
